//   「2 2 7 | i」として、導音から上の主音へ解決させる（docs/adr/0015-furusato.md）。
//
// 和声（下書き）：和音は I（1 3 5）、IV（4 6 i）、V（5 7 2）。旋律の上下を行き来させ、3 度・6 度と
//   和音の構成音で支える。同時に鳴るのは 2 音まで。旋律と同じ音（同じサイレン）は重ねない。
